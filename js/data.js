/* تحميل / حفظ */
let DB = (function load(){
  try{
    const raw = localStorage.getItem(DB_KEY);
    if(raw){
      const parsed = JSON.parse(raw);
      if(parsed && parsed.sections) return parsed;
    }
  }catch(e){ console.warn('تعذر تحميل قاعدة البيانات — سيتم إنشاء نسخة جديدة', e); }
  const fresh = clone(DEFAULT_DB);
  try{ localStorage.setItem(DB_KEY, JSON.stringify(fresh)); }catch(e){}
  return fresh;
})();

function saveDB(db){
  try{ localStorage.setItem(DB_KEY, JSON.stringify(db || DB)); }
  catch(e){ alert('تعذر الحفظ: المساحة ممتلئة. صغّر حجم اللوجو أو صدّر نسخة احتياطية ثم نظّف البيانات.'); }
}

